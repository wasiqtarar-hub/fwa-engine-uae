def _report_files_stale(result) -> str:
    source = _report_source()
    current = str(getattr(result, "source_name", "") or active_dataset().name)
    if source and current and source != current:
        return (f"The report files below were generated from {source}, not from {current}, the "
                "file in use now. The summary above describes the file in use; regenerate the "
                "reports to bring the files in line.")
    return ""


def _regenerate(result, state, *, label: str, primary: bool = False) -> None:
    if not state.can(Permission.RUN_PIPELINE):
        st.caption("Your role cannot regenerate the reports. An analyst or administrator can.")
        return
    if st.button(label, type="primary" if primary else "secondary", key=f"regen_{primary}",
                 help="Rewrites every report file from the run the app is showing now. Use it "
                      "after loading a different file, so the files match the summary. It takes "
                      "about a minute."):
        from fwa.evaluation import ReportBuilder

        with friendly_failure("the report regeneration",
                              "Try again. If it keeps failing, ask an administrator to check the "
                              "application log and that the reports folder can be written to."):
            with st.spinner("Regenerating every report file…"):
                written = ReportBuilder(result, REPORTS).build_all()
            st.success(f"Regenerated {len(written)} report files from the file in use.")


def _technical(result, state) -> None:
    st.markdown("## Full technical report")
    stale = _report_files_stale(result)
    if stale:
        st.warning(stale)
    path = REPORTS / "validation_report.md"
    if not path.exists():
        empty_state("No report has been generated yet",
                    "Press the button below, or run "
                    "`python -m fwa.run_validation` from the project folder. The run is "
                    "deterministic: fixed seed, recorded fingerprint.")
        _regenerate(result, state, label="Generate the reports now", primary=True)
        return
    chosen = st.selectbox(
        "Report", list(MARKDOWN_ARTEFACTS), key="vr_markdown",
        help="What it does: picks which written report to read. When to change it: the "
             "validation report is the main one; the model card covers the pattern-finding "
             "models, and 'Limitations' lists everything the run cannot show.",
    )
    target = REPORTS / MARKDOWN_ARTEFACTS[chosen]
    if not target.exists():
        empty_state("Not generated", f"{target.name} was not produced by the last run. "
                                     "Regenerate the reports to create it.")
    else:
        text = target.read_text(encoding="utf-8")
        st.caption(words("artefacts").get(target.name, ""))
        st.download_button(f"Download {target.name}", text, file_name=target.name,
                           mime="text/markdown", key="vr_md_download",
                           help="Saves this report as a text file with simple formatting.")
        st.markdown("---")
        st.markdown(text)
    st.markdown("---")
    _regenerate(result, state, label="Regenerate all reports from the current run")


def _files(result, state) -> None:
    st.markdown("## Supporting files")
    st.caption("Every table behind the reports, as a spreadsheet file. Each number in them is a "
               "measured output of this run, a threshold labelled as such, or marked as not "
               "measurable on this file.")
    if not REPORTS.exists():
        empty_state("No report files yet", "Generate the reports on the previous tab first.")
        return
    stale = _report_files_stale(result)
    if stale:
        st.warning(stale)
    chosen = st.selectbox(
        "File", list(CSV_ARTEFACTS), key="vr_csv",
        help="What it does: picks which supporting table to preview and download. When to "
             "change it: the control coverage matrix lists all 164 checks; the metrics file "
             "lists every measure, including the ones that cannot be measured yet.",
    )
    path = REPORTS / CSV_ARTEFACTS[chosen]
    if not path.exists():
        empty_state("Not generated", f"{path.name} was not produced by the last run. "
                                     "Regenerate the reports to create it.")
        return
    st.caption(words("artefacts").get(path.name, ""))
    with friendly_failure(f"the file {path.name}", "Regenerate the reports and try again."):
        frame = pd.read_csv(path)
        st.download_button(f"Download {path.name}", path.read_bytes(), file_name=path.name,
                           mime="text/csv", key="vr_csv_download",
                           help="Saves this table for a spreadsheet.")
        if "status" in frame.columns:
            counts = frame["status"].value_counts()
            st.markdown(" ".join(status_chip(str(k)) + f" {v}" for k, v in counts.items()),
                        unsafe_allow_html=True)
        dataframe(frame, height=520)
    with st.expander("Technical details: run identity", expanded=False):
        dataframe(pd.DataFrame([
            {"item": "Seed (cfg.random_seed)", "value": str(result.seed)},
            {"item": "Parameter fingerprint (stamped onto every signal)",
             "value": result.config.fingerprint()},
            {"item": "Files in reports/", "value": str(len(list(REPORTS.glob("*"))))},
        ]))


# ---------------------------------------------------------------------------
# page
# ---------------------------------------------------------------------------


def render() -> None:
    state = require_page("Validation Report", Permission.VIEW_VALIDATION_REPORT)
    session_banner(state)
    page_header("Validation Report")
    banner()
    synthetic_banner()

    result = pipeline()

    tab_summary, tab_report, tab_files = st.tabs(
        ["Summary", "Full technical report", "Supporting files"])
    with tab_summary:
        with friendly_failure("the plain summary"):
            _summary(result)
    with tab_report:
        with friendly_failure("the technical report"):
            _technical(result, state)
    with tab_files:
        with friendly_failure("the supporting files"):
            _files(result, state)
