"""Validation Report — a one-screen plain summary, then the §11.2 artefacts in full.

The summary at the top is computed from the run every other page is showing,
not read out of the report files, so it cannot disagree with the rest of the
app. It says, in words: which file, how many claims, how many checks ran fully,
in a simplified form or not at all, how many cases and what they suggest, the
money involved split into established and not-yet-established (never added),
the models' status, and what cannot be measured yet and why. Nothing in it is a
number the engine did not measure.

The full technical report and every downloadable artefact sit on the later
tabs, unchanged, and can be regenerated from the current run.
"""

from __future__ import annotations

import html
import re

import pandas as pd
import streamlit as st

from common import (
    ROOT, banner, dataframe, empty_state, friendly_failure, headline_cards, note, page_header,
    pipeline, require_page, session_banner, status_chip, synthetic_banner,
)
from components.data_help import (
    adapter_labels, coverage, dataset_info, disposition_sentence, exposure_split,
    model_sentences, money, plural, unmeasurable, words,
)
from dataset import active_dataset
from fwa.auth import Permission
from fwa.presentation import standard_text

REPORTS = ROOT / "reports"

MARKDOWN_ARTEFACTS = {
    "Validation report": "validation_report.md",
    "Release-gate report": "release_gate_report.md",
    "Model card": "model_card.md",
    "Limitations": "limitations.md",
}

CSV_ARTEFACTS = {
    "Control coverage matrix (all 164 controls)": "control_coverage_matrix.csv",
    "Traceability matrix (Appendix D, regenerated from code)": "traceability_matrix.csv",
    "Operational metrics": "metrics.csv",
    "Evaluation protocol": "evaluation_protocol.csv",
    "Precision by ground-truth source": "precision_by_ground_truth_source.csv",
    "Recall by fraud type": "recall_by_fraud_type.csv",
    "Parameter registry": "parameter_registry.csv",
    "Canonical population report": "canonical_population_report.csv",
    "Control run report": "control_run_report.csv",
    "Case queue": "case_queue.csv",
}

_SOURCE = re.compile(r"Source `([^`]+)`")


def _run_gate_if_needed(result) -> None:
    """The same checklist run the Pattern-finding models page does, so the summary can say it."""
    layer = getattr(result, "models", None)
    anomaly = getattr(layer, "anomaly", None) if layer is not None else None
    if anomaly is None or not getattr(anomaly, "models", None) or layer.gate_verdicts:
        return
    from fwa.evaluation import MetricSuite

    config = result.config
    capacity = max(int(config.get("alerts_per_reviewer_per_day"))
                   * int(config.get("reviewer_count")), 1)
    layer.run_gate(outcomes=MetricSuite(result).provider_outcomes(), capacity=capacity)


def _report_source() -> str:
    path = REPORTS / "validation_report.md"
    try:
        head = path.read_text(encoding="utf-8")[:2000]
    except Exception:
        return ""
    m = _SOURCE.search(head)
    return m.group(1) if m else ""


