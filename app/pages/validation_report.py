# the plain summary
# ---------------------------------------------------------------------------


def _summary(result) -> None:
    spec = active_dataset()
    info = dataset_info(spec)
    cov = coverage(result)
    claims = len(result.claims)
    cases = len(result.cases.cases)
    flags = len(result.signals)
    established, not_established, n_est, n_not = exposure_split(result)
    adapter = adapter_labels().get(spec.adapter, spec.adapter)

    st.markdown("## Summary in plain English")
    headline_cards([
        (f"{claims:,}", "claims in the file this report describes."),
        (f"{cov.full + cov.simplified:,} of {cov.total:,}",
         f"checks could run ({cov.full:,} fully, {cov.simplified:,} in a simplified form)."),
        (f"{cases:,}", "cases for review. Each is a reason to look, not proof of fraud."),
        (money(established), f"established across {plural(n_est, 'case')}: a clear rule failed."),
        (money(not_established), f"not yet established, across {plural(n_not, 'case')}. "
                                 "Shown separately and never added to the figure before."),
    ])

    synthetic = " It is SYNTHETIC: generated by a program to exercise the engine." \
        if info.get("synthetic") else ""
    lines = [
        f"**What was run.** Every check and model ran over **{html.escape(str(info['name']))}** "
        f"({html.escape(spec.name)}, {claims:,} claims, read as {html.escape(adapter)}).{synthetic}",
        f"**Which checks could run.** {cov.headline()}",
        f"**What it found.** {flags:,} flags, grouped into {cases:,} cases for review. "
        + (f"Of the cases, {disposition_sentence(result)} " if cases else "")
        + html.escape(standard_text("not_proof")) + " "
        + html.escape(standard_text("priority_not_decision")),
        f"**Money involved.** {money(established)} is established, because a clear rule failed. "
        f"Separately, {money(not_established)} is not yet established: it is the full value of "
        "claims that look unusual. The two are never added together. "
        + html.escape(standard_text("not_savings")),
    ]
    for line in lines:
        st.markdown(line)

    st.markdown("**The pattern-finding models.**")
    with friendly_failure("the models' status"):
        _run_gate_if_needed(result)
    for sentence in model_sentences(result):
        st.markdown(f"- {sentence}")

    gaps = unmeasurable(result)
    if gaps:
        by_reason: dict[str, list[str]] = {}
        for name, why in gaps:
            by_reason.setdefault(why, []).append(name)
        bullets = "\n".join(f"- {', '.join(names)}: because {why}."
                            for why, names in by_reason.items())
        st.markdown(
            "**What cannot be measured yet.** The engine shows these as 'can't be measured yet' "
            "rather than inventing a number. How often a flag turns out to be a real problem "
            "needs reviewers' decisions, and none has been recorded on this run.\n\n" + bullets)
    else:
        st.markdown("**What cannot be measured yet.** How often a flag turns out to be a real "
                    "problem needs reviewers' decisions, and none has been recorded on this run, "
                    "so it is not reported as a number.")

    closing = standard_text("shadow")
    if info.get("synthetic"):
        closing += (" A check or model that passes on data built to pass it is a test of the "
                    "check, not evidence that it detects fraud.")
    note(closing)


